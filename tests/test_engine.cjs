const assert=require('node:assert/strict');
const fs=require('fs');
const P=require('../frontend/js/wealth-engine.js');
const data=P.migrate(JSON.parse(fs.readFileSync(__dirname+'/../frontend/data/mock-data.json','utf8')));
const eq=(x,y,epsilon=.00001)=>assert.ok(Math.abs(x-y)<epsilon,`${x} !== ${y}`);
assert.equal(data.assets.length,11);
assert.equal(data.holdings.length,11);
assert.ok(data.transactions.length>=15);
assert.equal(P.reconcile(data).tradeCount>=14,true);
const origHolding=data.holdings.find(x=>x.id==='pos-002');
const add=P.applyTransaction(data,{id:'test-new',assetId:'pos-002',action:'buy',date:'2026-10-10',quantity:100,price:120,fee:10,tax:0,fxRate:1,bankId:'bank-001'});
const newer=add.holdings.find(x=>x.id==='pos-002');
eq(newer.quantity,origHolding.quantity+100);
eq(add.bankAccounts.find(x=>x.id==='bank-001').balance,data.bankAccounts.find(x=>x.id==='bank-001').balance-12010);
eq(P.removeTransaction(add,'test-new').bankAccounts.find(x=>x.id==='bank-001').balance,data.bankAccounts.find(x=>x.id==='bank-001').balance);
eq(P.removeTransaction(add,'test-new').holdings.find(x=>x.id==='pos-002').quantity,origHolding.quantity);
const sell=P.applyTransaction(data,{id:'test-sell',assetId:'pos-001',action:'sell',date:'2026-10-10',quantity:10,price:1100,fee:10,tax:25,fxRate:1,bankId:''});
eq(sell.holdings.find(x=>x.id==='pos-001').quantity,140);
assert.ok(P.reconcile(sell).realizedTwd>P.reconcile(data).realizedTwd);
assert.throws(()=>P.applyTransaction(data,{id:'test-too-many',assetId:'pos-001',action:'sell',date:'2026-10-10',quantity:151,price:1100,fee:0,tax:0,fxRate:1,bankId:''}),/超過/);
const testLedger=P.applyTransaction(data,{id:'sell-all',assetId:'pos-001',action:'sell',date:'2026-10-10',quantity:150,price:1100,fee:0,tax:0,fxRate:1,bankId:''});assert.throws(()=>P.removeTransaction(testLedger,'opening-pos-001'),/超過/);
const flow=P.applyFlow(data,{id:'test-flow',kind:'expense',description:'test',category:'生活',date:'2026-10-10',currency:'TWD',amount:3500,fxRate:1,bankId:'bank-001'});
eq(flow.bankAccounts.find(x=>x.id==='bank-001').balance,data.bankAccounts.find(x=>x.id==='bank-001').balance-3500);
eq(P.removeFlow(flow,'test-flow').bankAccounts.find(x=>x.id==='bank-001').balance,data.bankAccounts.find(x=>x.id==='bank-001').balance);
const stats=P.finance(data);assert.ok(stats.gross>stats.net);assert.ok(stats.cashFlows.monthlyExpense>0);
const perf=P.performance(data.performanceEvents);assert.ok(perf.available);assert.ok(perf.xirrPct!==null);assert.equal(perf.end,'2026-10-10');
const fixed=P.performance([{date:'2025-01-01',beforeValueTwd:100000,externalFlowTwd:0},{date:'2026-01-01',beforeValueTwd:110000,externalFlowTwd:0}]);
eq(fixed.twrPct,10,.01);assert.ok(Math.abs(fixed.xirrPct-10)<.15);
const flowed=P.performance([{date:'2025-01-01',beforeValueTwd:100000,externalFlowTwd:0},{date:'2025-07-01',beforeValueTwd:110000,externalFlowTwd:50000},{date:'2026-01-01',beforeValueTwd:176000,externalFlowTwd:0}]);
eq(flowed.twrPct,21,.01);
assert.ok(flowed.xirrPct>0);
assert.equal(P.performance([]).available,false);
assert.equal(P.xirr([{date:'2025-01-01',amount:500},{date:'2026-01-01',amount:1000}]),null);
const noData=P.comparePerformance([],[]);assert.equal(noData.available,false);
assert.equal(P.comparePerformance(data.performanceEvents,data.performanceEvents).available,true);
assert.ok(P.goalForecast({targetTwd:500000,monthlyContribution:10000,annualReturnPct:0},0).months===50);
assert.ok(P.goalForecast({targetTwd:500000,monthlyContribution:0,annualReturnPct:0},0).months===null);
console.log('PASS: 23 assertions — migration, FIFO chronological validation, moving-average basis, fees, bank settlement/reversal, cashflow, TWR, XIRR, stress, goals, compare');
